const LABELS = ['A', 'B', 'C', 'D', 'E'];

async function main() {
  const adapter = new PrismaPg({ connectionString: process.env.DATABASE_URL });
  const prisma = new PrismaClient({ adapter });

  let choiceN = 0, fillN = 0;
  for (const c of CHOICE) {
    const p = await prisma.problem.findUnique({ where: { token: c.tok }, select: { id: true } });
    if (!p) { console.log(`  ⚠ ${c.tok} олдсонгүй — алгаслаа`); continue; }
    console.log(`  ↻ ${c.tok} — статемент + 5 сонголт (зөв: ${LABELS[c.correct]})`);
    if (COMMIT) {
      await prisma.$transaction([
        prisma.problemChoice.deleteMany({ where: { problemId: p.id } }),
        prisma.problem.update({
          where: { id: p.id },
          data: {
            statementText: c.st,
            choices: null,
            correctAnswer: c.opts[c.correct], // хүн уншихад: зөв сонголтын текст
            choiceOptions: {
              create: c.opts.map((text, i) => ({
                label: LABELS[i], text, order: i + 1,
                isCorrect: i === c.correct,
                mistakeType: i === c.correct ? 'NONE' : 'OTHER',
              })),
            },
          },
        }),
      ]);
    }
    choiceN++;
  }
  for (const f of FILL) {
    const p = await prisma.problem.findUnique({ where: { token: f.tok }, select: { id: true } });
    if (!p) { console.log(`  ⚠ ${f.tok} олдсонгүй — алгаслаа`); continue; }
    console.log(`  ↻ ${f.tok} — статемент цэвэрлэв (нүхний хариу хэвээр)`);
    if (COMMIT) {
      await prisma.problem.update({ where: { id: p.id }, data: { statementText: f.st } });
    }
    fillN++;
  }

  console.log(`\nДҮН: сонголттой ${choiceN}, нөхөх ${fillN}${COMMIT ? '' : '  (ХУУРАЙ — --commit-той дахин ажиллуулна)'}`);
  await prisma.$disconnect();
}
main().catch((e) => { console.error(e); process.exit(1); });
