-- Математикийн элсэлтийн цонхны availability-г засах.
--
-- ШАЛТГААН: production дээр Математик 'CLASSROOM_ONLY' болсон байсан бөгөөд энэ нь
-- эзний дүрэмтэй зөрчилдөнө — Математикийг ТАНХИМ БА ОНЛАЙН хоёуланд заадаг.
-- Буруу утгатай үед онлайн сурагч математикт бүртгүүлж чадахгүй болно.
-- (Анхны migration нь 'BOTH' гэж оруулсан хэдий ч production-ы бодит утга зөрсөн.)
--
-- Энэ нь НЭГ УДААГИЙН засвар: migration дахин ажиллахгүй тул хожим админ
-- панелаас санаатайгаар өөрчилсөн утгыг дарж бичихгүй.
UPDATE "EnrollmentWindow"
SET "availability" = 'BOTH', "updatedAt" = CURRENT_TIMESTAMP
WHERE "subject" = 'MATH' AND "availability" <> 'BOTH';
