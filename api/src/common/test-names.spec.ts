import { groupTestNames, regroupTopicText } from './test-names';

describe('groupTestNames', () => {
  it('нэг сэдвийн дугаартай тестүүд нэг бүлэг', () => {
    expect(
      groupTestNames([
        'Квадрат тэгшитгэлийн шийдийн хамаарал 1',
        'Квадрат тэгшитгэлийн шийдийн хамаарал 2',
        'Квадрат тэгшитгэлийн шийдийн хамаарал 3',
      ]),
    ).toBe('Квадрат тэгшитгэлийн шийдийн хамаарал 1, 2, 3');
  });

  it('өөр сэдвүүд «; »-оор тусдаа, дараалал хадгалагдана', () => {
    expect(
      groupTestNames([
        'Иррационал тэгшитгэл 4',
        'Иррационал тэгшитгэл 5',
        'Иррационал тэгшитгэл 6',
        'Илтгэгч тэгшитгэл 1',
        'Илтгэгч тэгшитгэл 2',
        'Илтгэгч тэгшитгэл 3',
        'Илтгэгч тэгшитгэл 4',
      ]),
    ).toBe('Иррационал тэгшитгэл 4, 5, 6; Илтгэгч тэгшитгэл 1, 2, 3, 4');
  });

  it('ганц нэр, хоосон жагсаалт', () => {
    expect(groupTestNames(['Тоо тоолол 1'])).toBe('Тоо тоолол 1');
    expect(groupTestNames([])).toBe('');
    expect(groupTestNames(['', '  '])).toBe('');
  });

  it('олон оронтой тоо («10») ба тоон дараалал бичсэнээрээ', () => {
    expect(
      groupTestNames(['Тоо тоолол 9', 'Тоо тоолол 10', 'Тоо тоолол 11']),
    ).toBe('Тоо тоолол 9, 10, 11');
    expect(groupTestNames(['Тоо тоолол 3', 'Тоо тоолол 1'])).toBe(
      'Тоо тоолол 3, 1',
    );
  });

  it('тоогүй нэр бие даана, тоотой бүлэгтэй нийлэхгүй', () => {
    expect(
      groupTestNames([
        'Илтгэгч тэгшитгэл',
        'Илтгэгч тэгшитгэл 1',
        'Илтгэгч тэгшитгэл 2',
        'Иррац шалгалт',
      ]),
    ).toBe('Илтгэгч тэгшитгэл; Илтгэгч тэгшитгэл 1, 2; Иррац шалгалт');
  });

  it('угтвар суурь нэр өөр бүлэг («Тэгшитгэл» ба «Тэгшитгэл систем»)', () => {
    expect(
      groupTestNames([
        'Тэгшитгэл 1',
        'Тэгшитгэл систем 1',
        'Тэгшитгэл 2',
        'Тэгшитгэл систем 2',
      ]),
    ).toBe('Тэгшитгэл 1, 2; Тэгшитгэл систем 1, 2');
    expect(
      groupTestNames(['Рациональ тэгшитгэл 1', 'Рациональ тэнцэтгэл биш 1']),
    ).toBe('Рациональ тэгшитгэл 1; Рациональ тэнцэтгэл биш 1');
  });

  it('холилдсон дараалал — бүлэг анх гарсан байрандаа', () => {
    expect(groupTestNames(['А 1', 'Б 1', 'А 2'])).toBe('А 1, 2; Б 1');
  });

  it('давхардал, илүү хоосон зай, зөвхөн тоо', () => {
    expect(groupTestNames(['Модуль  1', 'Модуль 1', ' Модуль 2 '])).toBe(
      'Модуль 1, 2',
    );
    expect(groupTestNames(['5', '5', 'Сэдэв'])).toBe('5; Сэдэв');
    expect(groupTestNames(['Тест 1A', 'Тест 1B'])).toBe('Тест 1A; Тест 1B');
  });

  it('хуучин «, »-тэй гарчгийг товчилно, чөлөөт бичвэрийг эвдэхгүй', () => {
    expect(regroupTopicText('Урвуу функц 1, Урвуу функц 2')).toBe(
      'Урвуу функц 1, 2',
    );
    expect(regroupTopicText('Урвуу функц 1, Модуль 3')).toBe(
      'Урвуу функц 1, Модуль 3',
    );
    expect(regroupTopicText('Давталт, шалгалт')).toBe('Давталт, шалгалт');
    expect(regroupTopicText('Урвуу функц 1, 2')).toBe('Урвуу функц 1, 2');
    expect(regroupTopicText(null)).toBe('');
    expect(regroupTopicText('Сэдэв')).toBe('Сэдэв');
  });
});
