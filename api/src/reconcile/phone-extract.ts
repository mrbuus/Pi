/**
 * Монгол утасны дугаарыг текстээс олох
 *
 * Монгол утасны формат: 8 оронтой, 5-9-өөр эхлэнэ
 * Префикс дэмждэг: +976, 976 (сонголтой)
 * Байршил: урд/дунд/хойно хаа сайгүй, тэмдэгтээр наалдсан ч олно
 *
 * @example
 * extractPhones("99887766aav") → ["99887766"]
 * extractPhones("Утас: 88112233 эсвэл +97699887766") → ["88112233", "99887766"]
 * extractPhones("+97688112233") → ["88112233"]
 */
export function extractPhones(description: string): string[] {
  if (!description || typeof description !== 'string') {
    return [];
  }

  const phones: string[] = [];

  // 1. Залгаа 8 орон:
  // - 5-9 эхэлнэ, 7 орон дагана
  // - +976 эсвэл 976 префиксийн сонголт
  // - өмнө/хойно нь цифр байхгүй → 881122334 шиг 9 оронд таарахгүй
  // Lookbehind нь ПРЕФИКСИЙН урд байх ёстой — префиксийн дараа тавибал
  // «+976»-ийн сүүлийн 6 цифр нь өөрөө lookbehind-ийг унагаадаг.
  const solid = /(?<!\d)(?:\+?976)?([5-9]\d{7})(?!\d)/g;
  let match;
  while ((match = solid.exec(description)) !== null) {
    phones.push(match[1]);
  }

  // 2. ХУВААГДСАН дугаар — Хаан банкны бодит хуулгад тааралддаг
  //    («Батсуурь. Аззаяа 9976 3589» → 99763589).
  //    Зөвхөн 4+4 хэлбэр, дундаа НЭГ зай/зураас, эргэн тойрондоо цифргүй —
  //    үүнээс сул дүрэм тавивал «150000 40000» шиг дүнгүүд утас болж хуурна.
  const split = /(?<!\d)([5-9]\d{3})[ -](\d{4})(?!\d)/g;
  while ((match = split.exec(description)) !== null) {
    phones.push(match[1] + match[2]);
  }

  // Давхардлыг нэгтгэнэ (Set-аар)
  return [...new Set(phones)];
}
