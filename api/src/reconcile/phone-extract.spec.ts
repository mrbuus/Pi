import { extractPhones } from './phone-extract';

describe('extractPhones', () => {
  // Суурь хэрэглээ
  describe('8 оронтой дугаар', () => {
    it('чэвэр дугаарыг олно', () => {
      expect(extractPhones('88112233')).toEqual(['88112233']);
    });

    it('5-өөр эхэлсэн дугаарыг олно', () => {
      expect(extractPhones('51234567')).toEqual(['51234567']);
    });

    it('9-өөр эхэлсэн дугаарыг олно', () => {
      expect(extractPhones('99887766')).toEqual(['99887766']);
    });
  });

  describe('префикс цэвэрлэх', () => {
    it('+976 префикстэй дугаарыг цэвэрлэнэ', () => {
      expect(extractPhones('+97688112233')).toEqual(['88112233']);
    });

    it('976 префикстэй дугаарыг цэвэрлэнэ', () => {
      expect(extractPhones('97688112233')).toEqual(['88112233']);
    });

    it('префиксгүй дугаарыг сайнаар ажиллуулна', () => {
      expect(extractPhones('88112233')).toEqual(['88112233']);
    });
  });

  describe('тэмдэгтээр наалдсан дугаар', () => {
    it('үсэг дараа байх дугаарыг олно', () => {
      expect(extractPhones('99887766aav')).toEqual(['99887766']);
    });

    it('тэмдэгтээр эхэлсэн дугаарыг олно', () => {
      expect(extractPhones('utas:88112233')).toEqual(['88112233']);
    });

    it('хаш тэмдэгтээр наалдсан дугаарыг олно', () => {
      expect(extractPhones('phone#77123456')).toEqual(['77123456']);
    });

    it('доогуур зураасаар наалдсан дугаарыг олно', () => {
      expect(extractPhones('user_88112233_pay')).toEqual(['88112233']);
    });

    it('хоосон зайгаар тусгаарласан дугаарыг олно', () => {
      expect(extractPhones('утас 88112233 төлбөр')).toEqual(['88112233']);
    });
  });

  describe('урт шалгалт', () => {
    it('7 оронтой дугаарыг БҮҮ олна', () => {
      expect(extractPhones('8811223')).toEqual([]);
    });

    it('9 оронтой дугаарыг БҮҮ олна', () => {
      expect(extractPhones('912345678')).toEqual([]);
    });

    it('10 оронтой дугаарыг БҮҮ олна', () => {
      expect(extractPhones('9123456789')).toEqual([]);
    });
  });

  describe('эхлээрийн цифр шалгалт (5-9 байх ёстой)', () => {
    it('1-ээр эхэлсэн дугаарыг БҮҮ олна', () => {
      expect(extractPhones('11234567')).toEqual([]);
    });

    it('2-оор эхэлсэн дугаарыг БҮҮ олна', () => {
      expect(extractPhones('21234567')).toEqual([]);
    });

    it('3-аар эхэлсэн дугаарыг БҮҮ олна', () => {
      expect(extractPhones('31234567')).toEqual([]);
    });

    it('4-өөр эхэлсэн дугаарыг БҮҮ олна', () => {
      expect(extractPhones('41234567')).toEqual([]);
    });

    it('0-ээр эхэлсэн дугаарыг БҮҮ олна', () => {
      expect(extractPhones('01234567')).toEqual([]);
    });
  });

  describe('олон дугаар', () => {
    it('олон дугаарыг олно', () => {
      expect(extractPhones('88112233 99887766 77123456')).toEqual([
        '88112233',
        '99887766',
        '77123456',
      ]);
    });

    it('таслалаар тусгаарласан дугаарыг олно', () => {
      expect(extractPhones('88112233, 99887766, 77123456')).toEqual([
        '88112233',
        '99887766',
        '77123456',
      ]);
    });

    it('префиксгүй болон префикстэй холилсон дугаарыг олно', () => {
      expect(
        extractPhones('+97688112233 99887766 976 77123456'),
      ).toEqual(['88112233', '99887766', '77123456']);
    });
  });

  describe('давхардал нэгтгэх', () => {
    it('давхардсан дугаарыг нэгтгэнэ', () => {
      expect(extractPhones('88112233 88112233')).toEqual(['88112233']);
    });

    it('давхардсан хэд хэдэн дугаарыг нэгтгэнэ', () => {
      expect(extractPhones('88112233 99887766 88112233 99887766')).toEqual([
        '88112233',
        '99887766',
      ]);
    });

    it('префикс зөрөх давхардлыг нэгтгэнэ', () => {
      expect(extractPhones('+97688112233 976 88112233')).toEqual(['88112233']);
    });
  });

  describe('хоосон орц', () => {
    it('хоосон текстээс хоосон массив буцаана', () => {
      expect(extractPhones('')).toEqual([]);
    });

    it('ямар ч дугаар байхгүй текстээс хоосон массив буцаана', () => {
      expect(extractPhones('Энэ текстэд дугаар байхгүй')).toEqual([]);
    });

    it('null-ыг сайнаар зохицуулна', () => {
      expect(extractPhones(null as any)).toEqual([]);
    });

    it('undefined-ыг сайнаар зохицуулна', () => {
      expect(extractPhones(undefined as any)).toEqual([]);
    });
  });

  describe('бодит сценари', () => {
    it('гүйлгээний утга руу: "Төлбөр ирсэн. Утас: 88112233"', () => {
      expect(extractPhones('Төлбөр ирсэн. Утас: 88112233')).toEqual([
        '88112233',
      ]);
    });

    it('хүсэлтийн утга: "Сурагч 99887766 төлөв авна"', () => {
      expect(extractPhones('Сурагч 99887766 төлөв авна')).toEqual([
        '99887766',
      ]);
    });

    it('олон адресантын төлбөр: "Орлогын төлбөр: 88112233, 99887766"', () => {
      expect(extractPhones('Орлогын төлбөр: 88112233, 99887766')).toEqual([
        '88112233',
        '99887766',
      ]);
    });

    it('давхардсан утга эхэнд: "(88112233) төлбөр ирсэн, дахин (88112233)"', () => {
      expect(extractPhones('(88112233) төлбөр ирсэн, дахин (88112233)')).toEqual(
        ['88112233'],
      );
    });
  });
});

describe('extractPhones — хуваагдсан дугаар (Хаан банкны бодит хуулгаас)', () => {
  it('зайгаар хуваагдсан 4+4 дугаарыг нийлүүлнэ', () => {
    expect(extractPhones('Батсуурь. Аззаяа 9976 3589')).toEqual(['99763589']);
  });

  it('зураасаар хуваагдсан дугаарыг нийлүүлнэ', () => {
    expect(extractPhones('утас 8811-2233')).toEqual(['88112233']);
  });

  it('дүнгийн хослолыг утас гэж андуурахгүй (эхний бүлэг 5-9-өөр эхлээгүй)', () => {
    // «ХААНААС: 1500 0000» маягийн дүн — 1 гэж эхэлсэн тул утас БИШ
    expect(extractPhones('ХААНААС: 1500 0000 УЯНГА')).toEqual([]);
  });

  it('урт тооны дунд таарахгүй (эргэн тойрны цифрийн хамгаалалт)', () => {
    // 150000 99763589 — залгаа хэлбэр нь олдоно, харин 0000 9976 гэж андуурахгүй
    expect(extractPhones('дүн 150000, утас 99763589')).toEqual(['99763589']);
    expect(extractPhones('данс 5085523797')).toEqual([]);
  });

  it('залгаа ба хуваагдсан хоёул байвал хоёуланг олно', () => {
    expect(extractPhones('88112233 болон 9911 2233')).toEqual([
      '88112233',
      '99112233',
    ]);
  });
});
