import 'package:flutter_test/flutter_test.dart';

import 'rules/source_scan.dart';

/// Монгол хэлэнд бие даасан үг болж ХЭРЭГЛЭГДДЭГГҮЙ, орос хэлний түгээмэл үгс.
/// Монгол үгтэй давхцдаг («он», «да», «над», «там», «тест», «дата» …)-ыг санаатайгаар оруулаагүй.
const russianWords = <String>{
  'и', 'в', 'во', 'на', 'не', 'ни', 'по', 'из', 'от', 'при', 'для', 'без', 'под',
  'про', 'через', 'после', 'перед', 'между',
  'это', 'эти', 'этот', 'эта', 'что', 'как', 'если', 'или', 'когда', 'где',
  'почему', 'который', 'которые', 'все', 'всё', 'вы', 'мы', 'она', 'они',
  'уже', 'только', 'ещё', 'еще', 'тоже', 'также', 'очень', 'сейчас', 'здесь',
  'был', 'была', 'были', 'будет', 'есть', 'нужно', 'можно', 'нет',
  'ошибка', 'ошибки', 'загрузка', 'загрузки', 'загружается', 'сохранить',
  'сохранено', 'назад', 'далее', 'отмена', 'отменить', 'готово', 'удалить',
  'изменить', 'добавить', 'поиск', 'войти', 'выйти', 'вход', 'выход', 'пароль',
  'логин', 'пользователь', 'настройки', 'подождите', 'попробуйте', 'снова',
  'повторить', 'пожалуйста', 'спасибо', 'привет', 'здравствуйте',
  'понедельник', 'вторник', 'среда', 'четверг', 'пятница', 'суббота',
  'воскресенье', 'сегодня', 'вчера', 'завтра', 'неделя', 'месяц', 'год',
  'время', 'ответ', 'вопрос', 'задача', 'урок', 'класс', 'ученик', 'учитель',
  'родитель', 'оплата', 'задание', 'экзамен', 'хорошо', 'плохо', 'новый',
  'первый', 'второй', 'последний', 'следующий', 'предыдущий', 'больше', 'меньше',
};

final _cyrillicWord = RegExp('[А-Яа-яЁёӨөҮү]+');

void main() {
  test('lib/ дотор орос үг байхгүй', () {
    final hits = <String>[];
    for (final file in readSources(['lib', 'integration_test'])) {
      for (final (n, line) in file.lines) {
        for (final m in _cyrillicWord.allMatches(line)) {
          final word = m.group(0)!.toLowerCase();
          if (russianWords.contains(word)) {
            hits.add('${file.path}:$n  «${m.group(0)}»  $line'.trim());
          }
        }
      }
    }
    expect(hits, isEmpty, reason: 'Орос үг олдлоо:\n${hits.join('\n')}');
  });

  test('жагсаалт өөрөө монгол түгээмэл үгийг агуулахгүй', () {
    // Хуурамч дохио өгөхгүйн тулд: эдгээр нь монгол үг.
    for (final mn in ['он', 'да', 'над', 'там', 'тест', 'дата', 'ба', 'нь', 'бол']) {
      expect(russianWords.contains(mn), isFalse, reason: mn);
    }
  });
}
