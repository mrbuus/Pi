import { roomShapeOf, type RoomShapeKind } from "./types";

/**
 * Танхимын ХААЛГАН ДЭЭРХ бодит дүрс (501=бөөрөнхий, 502=гурвалжин, 503=трапец,
 * 504=квадрат, 403=ромбо, 404=таван өнцөгт, 405=тэгш өнцөгт, Онлайн=дэлгэц).
 *
 * ── Дизайны шийдэл (2026-08-07, эзний засвар) ──────────────────────────────
 *
 * БУДАЛТГҮЙ. Өмнө нь дотор нь ангийн өнгөөр 16% дүүргэдэг байсан ("duotone").
 * Эзний шаардлага: "дүрсийг нь будалгүй, хүн шууд хараад мэдэхээр ТОД".
 * Будалт нь жижиг хэмжээнд эсрэг үр дүн өгдөг — дүрсийн танигдах чадвар
 * СИЛУЭТИЙН ИРМЭГЭЭС хамаардаг тул дотоод дүүргэлт ирмэгийн контрастыг
 * бууруулж, квадрат/ромбо, трапец/гурвалжин хосыг ялгахад хүндрүүлдэг.
 *
 * ӨНГӨ НЬ ДҮРС ДЭЭР БАЙХГҮЙ. Дүрс `currentColor` (ink) — үргэлж дээд контраст.
 * Ангийн өнгө нь МӨРИЙН ЗҮҮН ЗУРВАС дээр очно (PatternOverview, WeekBuilder).
 * Ингэснээр "өнгө=анги, дүрс=танхим" давхар кодчилол хэвээр үлдэнэ, гэхдээ
 * ангийн өнгө цайвар байхад (жишээ нь #42d4f4) дүрс бүдгэрэхгүй.
 *
 * ГЕОМЕТР 24×24 сүлжээнд дахин зурагдсан (өмнө 16×16). Учир нь оройн цэгийг
 * нарийн байрлуулах нүсэр хэрэгтэй — 16 нэгжид 0.1 алдаа нь 16px дэлгэцэнд
 * бүтэн пиксел болж хазайдаг. Дүрс бүр ОПТИКААР ижил жинтэй болгож тааруулсан
 * (адил хүрээнд багтаасан тойрог нь квадратаас том харагддаг тул тойргийг
 * бага, ромбог томоор авсан).
 *
 * Хос хосоор нь ялгаруулсан газрууд:
 * - трапец vs гурвалжин → трапецын дээд тал ӨРГӨН (9.2 нэгж), таслагдсан
 *   гурвалжин биш, тодорхой хавтгай дээвэр болж уншигдана
 * - таван өнцөгт vs тойрог → оройнууд хурц (round join хэвээр, гэхдээ радиус
 *   том тул булангууд илт)
 * - квадрат vs ромбо → квадратын булангийн мурийлт 1.2 болж багассан
 *   (өмнө 2 байсан нь 10 нэгж дээр бөөндөж харагддаг байсан)
 */

/** 24×24 сүлжээ, төв (12,12). Дүрс бүр fill БАЙХГҮЙ — зөвхөн зураас. */
const SHAPE_PATHS: Record<RoomShapeKind, React.ReactNode> = {
  // 501 — тойрог. Оптикоор бага (r=8.2), эс бөгөөс бусдаас том харагдана.
  circle: <circle cx="12" cy="12" r="8.2" />,

  // 502 — гурвалжин. Гурвалжны хүндийн төв доогуур тул оройг 3.2 хүртэл өргөв.
  triangle: <path d="M12 3.2 L21.4 19.6 L2.6 19.6 Z" />,

  // 503 — трапец. Дээд тал 11.6 нэгж (доод талын 59%) — 16px дээр гурвалжингаас
  // эргэлзээгүй ялгарах хамгийн нарийн хил. 9.2 байхад (эхний хувилбар) жижиг
  // хэмжээнд "оройгоо тайруулсан гурвалжин" мэт уншигдаж байсан.
  // Өндөр нь гурвалжинтай ойролцоо (14.8 vs 16.4) — оптик жин тэнцвэртэй.
  trapezoid: <path d="M6.2 4.6 H17.8 L21.8 19.4 H2.2 Z" />,

  // 504 — квадрат. rx=1.2 — булан зөөлөрсөн ч дөрвөлжин хэвээр таних.
  square: <rect x="4.2" y="4.2" width="15.6" height="15.6" rx="1.2" />,

  // 405 — тэгш өнцөгт (хамгийн жижиг танхим). Өргөн, намхан — квадраттай
  // хэзээ ч андуурагдахгүй харьцаа (2:1).
  rect: <rect x="2.4" y="7.2" width="19.2" height="9.6" rx="1.2" />,

  // 404 — таван өнцөгт. Жинхэнэ зөв таван өнцөгт, r=9.4, төв (12,12.4).
  pentagon: <path d="M12 3 L20.9 9.5 L17.5 20 H6.5 L3.1 9.5 Z" />,

  // 403 — ромбо. Хагас диагональ 9.4 — квадратаас ТОМ (ромбо оптикоор жижиг).
  diamond: <path d="M12 2.6 L21.4 12 L12 21.4 L2.6 12 Z" />,

  // Онлайн — дэлгэц + хөл. Хөл нь дэлгэцийг телевизээс ялгана.
  online: (
    <>
      <rect x="2.6" y="4.6" width="18.8" height="12.4" rx="1.6" />
      <path d="M12 17 V20.4" />
      <path d="M8.4 20.4 H15.6" />
    </>
  ),
};

/**
 * Зураасны зузаан — ХЭМЖЭЭНЭЭС ХАМААРНА.
 *
 * 24 нэгжийн viewBox-ыг `size` пиксел рүү шахахад зураас ч хамт шахагдана.
 * Тогтмол `strokeWidth` үлдээвэл 16px дээр үс шиг нимгэн, 32px дээр бүдүүн
 * болно. Тиймээс хүссэн ОПТИК зузааныг (px) viewBox нэгж рүү буцааж хөрвүүлнэ.
 *
 * Жижиг дүрс харьцангуй БҮДҮҮН зураас шаарддаг (тод байх), том дүрс нимгэн
 * (гоолиг байх) — тиймээс шугаман биш.
 */
function strokePxFor(size: number): number {
  if (size <= 14) return 1.6;
  if (size <= 20) return 1.7;
  if (size <= 32) return 1.9;
  return 2.2;
}

export default function RoomShape({
  room,
  size = 16,
  className = "",
  color,
  title,
}: {
  room: string | null | undefined;
  size?: number;
  className?: string;
  /**
   * Зураасны өнгө. ӨГӨГДМӨЛ нь `currentColor` — эцэг элементийн текстийн
   * өнгийг авна (ink), ингэснээр контраст үргэлж дээд хэмжээнд байна.
   *
   * Ангийн өнгийг энд ДАМЖУУЛАХГҮЙ байхыг зөвлөнө — ангийн өнгө нь мөрийн
   * зурвас дээр очих ёстой (эзний шийдвэр 2026-08-07). Өнгөт дэвсгэр дээр
   * дүрсийг тусгайлан цайруулах шаардлагатай ховор тохиолдолд л ашиглана.
   */
  color?: string;
  /**
   * Дүрсийг ДАНГААР нь (дугаарын текстгүй) харуулах үед унших нэр.
   * Өгвөл дүрс `img` role авч, screen reader уншина. Өгөхгүй бол дугаар
   * хажууд нь байгаа гэж үзээд `aria-hidden` болно.
   */
  title?: string;
}) {
  const shape = roomShapeOf(room);
  if (!shape) return null;

  // viewBox 24 → size px. Хүссэн оптик зузааныг viewBox нэгж рүү хөрвүүлнэ.
  const strokeWidth = (24 / size) * strokePxFor(size);

  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke={color ?? "currentColor"}
      strokeWidth={strokeWidth}
      strokeLinejoin="round"
      strokeLinecap="round"
      shapeRendering="geometricPrecision"
      className={`shrink-0 ${className}`}
      {...(title ? { role: "img" as const, "aria-label": title } : { "aria-hidden": true })}
    >
      {title ? <title>{title}</title> : null}
      {SHAPE_PATHS[shape]}
    </svg>
  );
}
