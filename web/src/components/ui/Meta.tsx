import { Fragment, type ReactNode } from "react";

/**
 * Мета мэдээллийн ТУСГААРЛАГЧ.
 *
 * ── Яагаад «·» тэмдэгт биш вэ (эзний засвар 2026-08-08) ────────────────────
 *
 * Өмнө нь UI даяар `·` (U+00B7 MIDDLE DOT) тэмдэгтийг гараар бичиж
 * тусгаарлагч болгодог байсан — 130 гаруй газарт. Эзний шүүмж: «маш соёлгүй,
 * сонин бүдүүн хар цэг».
 *
 * Шалтгаан нь тэмдэгт өөрөө: `·` бол ФОНТЫН ГЛИФ. Фонт бүр өөр өөр диаметр,
 * өөр өндөрт зурдаг тул нэг дэлгэцэнд цэвэрхэн, нөгөөд нь бүдүүн бөөрөнхий
 * толбо болж харагдана. Хэрэглэгчийн фонт солигдвол бид хянах ямар ч аргагүй.
 *
 * Энд цэгийг CSS-ЭЭР ЗУРНА (`content: ""` + `border-radius`). Тэгснээр:
 *   • диаметр яг 3px — фонтоос үл хамаарна
 *   • тунгалаг 35% — мэдээллийг таслахгүй, зөвхөн зааглана
 *   • өнгө нь `currentColor` — гэрэл/харанхуй горимд аяндаа тохирно
 *   • дэлгэц уншигч юу ч уншихгүй (тэмдэгт биш, чимэглэл)
 *
 * Дүрмийг `globals.css`-ийн `.meta-dot` дотор бичсэн.
 */
export function Dot() {
  return <span className="meta-dot" aria-hidden />;
}

/**
 * Хэд хэдэн мета зүйлийг цэгээр зааглан харуулна.
 *
 *   <Meta items={[room, teacher, time]} />
 *
 * `null`/`undefined`/хоосон мөрийг ЧИМЭЭГҮЙ алгасна — дуудах газар бүрт
 * `{x && ...}` бичих шаардлагагүй, мөн «эхлээд цэг гараад дараа нь юу ч
 * байхгүй» гэсэн эвгүй байдал үүсэхгүй.
 */
export function Meta({
  items,
  className = "",
}: {
  items: ReactNode[];
  className?: string;
}) {
  const shown = items.filter(
    (x) => x !== null && x !== undefined && x !== false && x !== "",
  );
  if (shown.length === 0) return null;
  return (
    <span className={`inline-flex flex-wrap items-center ${className}`}>
      {shown.map((item, i) => (
        <Fragment key={i}>
          {i > 0 && <Dot />}
          {item}
        </Fragment>
      ))}
    </span>
  );
}

/**
 * ӨС-д хадгалагдсан гарчгийг цэвэрхэн харуулна.
 *
 * Импортын скриптүүд гарчигт `·`-ыг ШУУД БИЧИЖ хадгалсан
 * (ж: «Интеграл · Тест 1-A», «100x100 V2 · Логарифм 3»). Тэр тэмдэгт нь
 * одоо мянга мянган мөрөнд шингэсэн тул ӨС-ийг өөрчлөх нь эрсдэлтэй —
 * оронд нь ХАРУУЛАХ үед задалж, CSS цэгээр солино.
 *
 * Ингэснээр хуучин өгөгдөл ямар ч миграцгүйгээр цэвэрхэн харагдана.
 * Шинэ өгөгдөлд `·` бичихээ импортын скриптүүд дээр зогсоосон.
 */
export function MetaTitle({
  children,
  className = "",
}: {
  children: string | null | undefined;
  className?: string;
}) {
  if (!children) return null;
  // Зөвхөн ЗААГЛАГЧ цэгийг (хоёр талдаа зайтай) задална. Үгийн дунд орсон
  // цэгийг хөндөхгүй — ж. «а.б·в» гэх мэт ховор тохиолдолд гэмтээхгүй.
  const parts = children.split(/\s+·\s+/);
  if (parts.length === 1) return <span className={className}>{children}</span>;
  return <Meta className={className} items={parts} />;
}
