/**
 * Сурагчид харагдах тестийн нэр (эзэн 2026-10-29, шийдвэр 6): номын дотоод нэр
 * («100x100», «200×200», «V2», «V3») ХЭЗЭЭ Ч харуулахгүй, хувилбарын үсгийг гарчигт
 * давтахгүй. Эх нэрэн дэх «·» тусгаарлагчийг « — » болгоно (сурагчийн дэлгэцэнд «·»
 * бичихгүй — дүрэм, Meta.tsx). Хоосон үлдвэл `fallback`.
 */
export function cleanTitle(
  title: string,
  variantLabel?: string | null,
  fallback = "Даалгавар",
): string {
  let t = (title ?? "")
    // «100x100», «200 × 200», кирилл «х»
    .replace(/\b\d{2,4}\s*[xX×хХ]\s*\d{2,4}\b/g, " ")
    // «V2», «V3» гэх мэт хувилбарын код
    .replace(/(^|[\s·•—–:-])V\d\b/g, "$1")
    // «·» / «•» тусгаарлагч → « — »
    .replace(/\s*[·•]\s*/g, " — ");
  if (variantLabel) {
    const v = variantLabel.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    // Төгсгөлийн «-B», « B», «(B)», «B хувилбар»
    t = t.replace(new RegExp(`[\\s(-]*${v}\\)?(\\s*хувилбар)?\\s*$`, "i"), "");
  }
  t = t
    .replace(/\s{2,}/g, " ")
    // Давхардсан тусгаарлагч «А — — Б» → «А — Б»
    .replace(/(\s—)+\s—/g, " —")
    .replace(/^[\s—–:,-]+|[\s—–:,-]+$/g, "")
    .trim();
  return t || fallback;
}
